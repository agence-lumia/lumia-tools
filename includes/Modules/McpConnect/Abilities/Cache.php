<?php
namespace Lumia\Tools\Modules\McpConnect\Abilities;

defined( 'ABSPATH' ) || exit;

/**
 * `lumia/purge-cache`: after a change, Claude purges what would hide it (page
 * cache, object cache, OPcache, expired transients) before checking the page.
 */
final class Cache implements Family {

	/** Targets of a purge. */
	const TARGETS = [ 'page', 'object', 'opcache', 'transients' ];

	public static function label(): string {
		return __( 'Caches', 'lumia-tools' );
	}

	public static function description(): string {
		return __( 'Purge the page cache (Cache Enabler, WP Rocket, LiteSpeed and others), the object cache, OPcache and expired transients.', 'lumia-tools' );
	}

	public static function available(): bool {
		return true;
	}

	public static function definitions(): array {
		return [
			'purge-cache' => [
				'label'       => __( 'Purge the caches', 'lumia-tools' ),
				'description' => 'Purges the caches that would hide a change: page cache of the cache plugin in place (Cache Enabler, WP Rocket, LiteSpeed Cache, W3 Total Cache, WP Super Cache, WP Fastest Cache, SiteGround, Breeze, Nginx Helper), object cache (Redis, Memcached), OPcache and expired transients. `url` purges the page cache of that URL only, where the plugin allows it. The Bricks CSS files are regenerated by bricks/regenerate-css-files, not here.',
				'input'       => [
					'targets' => [
						'type'        => 'array',
						'items'       => [
							'type' => 'string',
							'enum' => self::TARGETS,
						],
						'description' => 'What to purge; every target when omitted.',
					],
					'url'     => [
						'type'        => 'string',
						'description' => 'Purge the page cache of this URL only (page target).',
					],
				],
				'execute'     => [ self::class, 'purge' ],
				'capability'  => 'manage_options',
				'readonly'    => false,
				'destructive' => false,
				'idempotent'  => true,
			],
		];
	}

	/**
	 * @param array<string, mixed> $args
	 * @return array<string, mixed>
	 */
	public static function purge( array $args ): array {
		$targets = isset( $args['targets'] ) && is_array( $args['targets'] ) && [] !== $args['targets']
			? array_values( array_intersect( self::TARGETS, $args['targets'] ) )
			: self::TARGETS;
		$url     = isset( $args['url'] ) ? esc_url_raw( (string) $args['url'] ) : '';
		$done    = [];

		if ( in_array( 'page', $targets, true ) ) {
			$done['page'] = self::purge_page( $url );
		}

		if ( in_array( 'object', $targets, true ) ) {
			$done['object'] = [
				'external' => wp_using_ext_object_cache(),
				'flushed'  => wp_cache_flush(),
			];
		}

		if ( in_array( 'opcache', $targets, true ) ) {
			$done['opcache'] = function_exists( 'opcache_reset' ) && @opcache_reset(); // phpcs:ignore WordPress.PHP.NoSilencedErrors.Discouraged -- restricted by opcache.restrict_api on some hosts: reported as false.
		}

		if ( in_array( 'transients', $targets, true ) ) {
			delete_expired_transients( true );
			$done['transients'] = true;
		}

		return $done;
	}

	/**
	 * Page caches whose purge function is loaded.
	 *
	 * @return string[]
	 */
	public static function detected_page_caches(): array {
		$found = [];
		foreach ( self::page_caches() as $name => $cache ) {
			if ( $cache['detect']() ) {
				$found[] = $name;
			}
		}

		return $found;
	}

	/**
	 * @return array{purged: string[], url: string, note?: string}
	 */
	private static function purge_page( string $url ): array {
		$purged = [];
		foreach ( self::page_caches() as $name => $cache ) {
			if ( ! $cache['detect']() ) {
				continue;
			}
			if ( '' !== $url && isset( $cache['url'] ) ) {
				$cache['url']( $url );
			} else {
				$cache['all']();
			}
			$purged[] = $name;
		}

		$result = [
			'purged' => $purged,
			'url'    => $url,
		];
		if ( [] === $purged ) {
			$result['note'] = 'No page cache plugin detected.';
		}

		return $result;
	}

	/**
	 * Calls a function of a cache plugin when it exists.
	 *
	 * @param string $name    Function name.
	 * @param mixed  ...$args Arguments.
	 */
	private static function call( string $name, ...$args ): void {
		if ( is_callable( $name ) ) {
			$name( ...$args );
		}
	}

	/**
	 * Known page caches: how to detect them, purge everything, purge one URL.
	 * Through their public actions and functions, never their files.
	 *
	 * @return array<string, array{detect: callable(): bool, all: callable(): void, url?: callable(string): void}>
	 */
	private static function page_caches(): array {
		// phpcs:disable WordPress.NamingConventions.PrefixAllGlobals.NonPrefixedHooknameFound -- the cache plugins' own hooks.
		return [
			'Cache Enabler'    => [
				'detect' => static function (): bool {
					return class_exists( '\Cache_Enabler' );
				},
				'all'    => static function (): void {
					do_action( 'cache_enabler_clear_complete_cache' );
				},
				'url'    => static function ( string $url ): void {
					do_action( 'cache_enabler_clear_page_cache_by_url', $url );
				},
			],
			'WP Rocket'        => [
				'detect' => static function (): bool {
					return function_exists( 'rocket_clean_domain' );
				},
				'all'    => static function (): void {
					self::call( 'rocket_clean_domain' );
				},
				'url'    => static function ( string $url ): void {
					self::call( 'rocket_clean_files', [ $url ] );
				},
			],
			'LiteSpeed Cache'  => [
				'detect' => static function (): bool {
					return defined( 'LSCWP_V' );
				},
				'all'    => static function (): void {
					do_action( 'litespeed_purge_all' );
				},
				'url'    => static function ( string $url ): void {
					do_action( 'litespeed_purge_url', $url );
				},
			],
			'W3 Total Cache'   => [
				'detect' => static function (): bool {
					return function_exists( 'w3tc_flush_all' );
				},
				'all'    => static function (): void {
					self::call( 'w3tc_flush_all' );
				},
				'url'    => static function ( string $url ): void {
					if ( function_exists( 'w3tc_flush_url' ) ) {
						self::call( 'w3tc_flush_url', $url );
					}
				},
			],
			'WP Super Cache'   => [
				'detect' => static function (): bool {
					return function_exists( 'wp_cache_clear_cache' );
				},
				'all'    => static function (): void {
					self::call( 'wp_cache_clear_cache' );
				},
			],
			'WP Fastest Cache' => [
				'detect' => static function (): bool {
					return function_exists( 'wpfc_clear_all_cache' );
				},
				'all'    => static function (): void {
					self::call( 'wpfc_clear_all_cache', true );
				},
			],
			'SiteGround'       => [
				'detect' => static function (): bool {
					return function_exists( 'sg_cachepress_purge_cache' );
				},
				'all'    => static function (): void {
					self::call( 'sg_cachepress_purge_cache' );
				},
				'url'    => static function ( string $url ): void {
					self::call( 'sg_cachepress_purge_cache', $url );
				},
			],
			'Breeze'           => [
				'detect' => static function (): bool {
					return class_exists( '\Breeze_PurgeCache' );
				},
				'all'    => static function (): void {
					do_action( 'breeze_clear_all_cache' );
				},
			],
			'Nginx Helper'     => [
				'detect' => static function (): bool {
					return class_exists( '\Nginx_Helper' );
				},
				'all'    => static function (): void {
					do_action( 'rt_nginx_helper_purge_all' );
				},
			],
		];
		// phpcs:enable
	}
}
